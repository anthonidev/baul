import Foundation
import Testing
@testable import BaulCore

@Suite struct CapturePolicyTests {
    let now = Date(timeIntervalSince1970: 1_800_000_000)

    func item(
        _ payload: CapturedItem.Payload = .text("hola"),
        bundleID: String? = "com.apple.Terminal",
        types: Set<String> = ["public.utf8-plain-text"]
    ) -> CapturedItem {
        CapturedItem(
            payload: payload,
            source: bundleID.map { SourceApp(bundleID: $0, name: "App") },
            pasteboardTypes: types,
            capturedAt: now
        )
    }

    @Test func `stores ordinary text`() {
        #expect(CapturePolicy().decide(item()) == .store)
    }

    @Test(arguments: [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ])
    func `skips content marked as private`(marker: String) {
        let decision = CapturePolicy().decide(item(types: ["public.utf8-plain-text", marker]))
        #expect(decision == .skip(.privacyMarker))
    }

    @Test func `skips excluded apps`() {
        let policy = CapturePolicy(excludedBundleIDs: ["com.bank.app"])
        #expect(policy.decide(item(bundleID: "com.bank.app")) == .skip(.excludedApp))
        #expect(policy.decide(item(bundleID: "com.apple.Terminal")) == .store)
    }

    @Test func `skips whitespace-only text`() {
        #expect(CapturePolicy().decide(item(.text("  \n\t "))) == .skip(.empty))
    }

    @Test func `skips images over the size limit`() {
        let policy = CapturePolicy(maxImageBytes: 10)
        #expect(policy.decide(item(.image(png: Data(count: 11), width: 1, height: 1))) == .skip(.tooLarge))
        #expect(policy.decide(item(.image(png: Data(count: 10), width: 1, height: 1))) == .store)
    }

    @Test func `respects pause until a date`() {
        let paused = CapturePolicy(pause: .paused(until: now.addingTimeInterval(60)))
        #expect(paused.decide(item()) == .skip(.paused))

        let expired = CapturePolicy(pause: .paused(until: now.addingTimeInterval(-1)))
        #expect(expired.decide(item()) == .store)

        let indefinite = CapturePolicy(pause: .paused(until: nil))
        #expect(indefinite.decide(item()) == .skip(.paused))
    }
}
